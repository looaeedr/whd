"""#1820 CADCraft v0.8.0: keep unused original *D block definitions.

An untouched DXF can contain orphan dimension graphics (*D1 ... *D4) that
still belong to the file even if no modelspace DIMENSION currently references
them. CADCraft's dim_block_plan() currently drops all unreferenced *D blocks.
This experimental source patch avoids that data loss without duplicating
referenced dimension blocks regenerated by the existing dimension writer.

Only patch separately checked-out upstream v0.8.0 source; never rewrite
original customer DXF or WHD manufacturing geometry.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

import ezdxf

UPSTREAM_RELATIVE = Path("crates/io/src/dxf_write.rs")
BEFORE = (
    "    let skip = d.blocks.keys().filter(|n| is_dim_block(n))"
    ".map(|n| n.to_ascii_uppercase())"
    ".filter(|n| !used.contains(n)).collect();"
)
AFTER = (
    "    // A modelspace dimension's old graphics block is regenerated below;\n"
    "    // only those actually attached to a dimension may be skipped here.\n"
    "    // Unreferenced original *D blocks must survive unchanged DXF resave.\n"
    "    let attached: std::collections::HashSet<String> = spaces.iter()\n"
    "        .flat_map(|s| s.iter())\n"
    "        .filter_map(|e| match &e.kind {\n"
    "            EntityKind::Dimension(dm) => dm.block.as_deref(),\n"
    "            _ => None,\n"
    "        })\n"
    "        .filter(|name| is_dim_block(name))\n"
    "        .map(str::to_ascii_uppercase)\n"
    "        .collect();\n"
    "    let skip = d.blocks.keys().filter(|n| is_dim_block(n))\n"
    "        .map(|n| n.to_ascii_uppercase())\n"
    "        .filter(|n| !used.contains(n) && attached.contains(n))\n"
    "        .collect();"
)
ORPHAN_NAME = "*D777"


def patch_upstream(root: Path) -> dict:
    path = Path(root) / UPSTREAM_RELATIVE
    content = path.read_text(encoding="utf-8")
    if content.count(BEFORE) != 1 or AFTER in content:
        raise ValueError("UPSTREAM_V080_DIM_BLOCK_PLAN_ANCHOR_MISMATCH")
    patched = content.replace(BEFORE, AFTER)
    path.write_text(patched, encoding="utf-8")
    return {
        "path": str(UPSTREAM_RELATIVE),
        "original_sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
        "patched_sha256": hashlib.sha256(patched.encode("utf-8")).hexdigest(),
        "scope": "preserve unreferenced *D block definitions only",
    }


def fixture(folder: Path) -> dict:
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "original_with_orphan_and_attached_dimension.dxf"
    doc = ezdxf.new("R2010", units=ezdxf.units.MM)
    orphan = doc.blocks.new(ORPHAN_NAME)
    orphan.add_line((2, 4), (37, 41))
    orphan.add_circle((7, 11), radius=3.25)
    dimension = doc.modelspace().add_linear_dim(
        base=(60, 25), p1=(0, 0), p2=(120, 0), angle=0
    )
    dimension.render()
    doc.saveas(path)
    loaded = ezdxf.readfile(path)
    assert ORPHAN_NAME in loaded.blocks
    attached = {
        d.dxf.geometry.upper()
        for d in loaded.modelspace().query("DIMENSION")
    }
    if ORPHAN_NAME in attached or not attached:
        raise ValueError("BROKEN_ORPHAN_BLOCK_FIXTURE")
    return {"source": str(path), "orphan": ORPHAN_NAME,
            "attached_dimension_blocks": sorted(attached)}


def verify(cli: Path, folder: Path, expected: str, evidence: Path) -> bool:
    source = Path(folder) / "original_with_orphan_and_attached_dimension.dxf"
    target = Path(folder) / f"{expected}_resaved.dxf"
    source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
    process = subprocess.run(
        [str(cli), "run", str(source), "--save", str(target)],
        capture_output=True, text=True, check=False, timeout=90,
    )
    report = {
        "kind": "CADCRAFT_V080_ORPHAN_DIMENSION_BLOCK_NATIVE_RED_GREEN",
        "expectation": expected,
        "cli_exit_code": process.returncode,
    }
    if process.returncode != 0 or not target.exists():
        report["error"] = process.stderr[-650:]
        ok = False
    else:
        a = ezdxf.readfile(source)
        b = ezdxf.readfile(target)
        original_names = {block.name.upper() for block in a.blocks}
        saved_names = {block.name.upper() for block in b.blocks}
        attached = {
            dim.dxf.geometry.upper()
            for dim in a.modelspace().query("DIMENSION")
        }
        retained_attached = {
            dim.dxf.geometry.upper()
            for dim in b.modelspace().query("DIMENSION")
        }
        source_orphan = a.blocks[ORPHAN_NAME]
        result_orphan = b.blocks[ORPHAN_NAME] if ORPHAN_NAME in saved_names else None
        report.update({
            "orphan_source": ORPHAN_NAME in original_names,
            "orphan_saved": ORPHAN_NAME in saved_names,
            "attached_original": sorted(attached),
            "attached_saved": sorted(retained_attached),
            "all_attached_resolve": bool(retained_attached)
                and retained_attached <= saved_names,
            "orphan_entity_geometry_equal": (
                _block_signature(source_orphan) == _block_signature(result_orphan)
                if result_orphan is not None else False
            ),
            "source_unchanged": (
                hashlib.sha256(source.read_bytes()).hexdigest() == source_hash
            ),
        })
        if expected == "baseline":
            ok = (not report["orphan_saved"]
                  and report["all_attached_resolve"]
                  and report["source_unchanged"])
        elif expected == "patched":
            ok = (report["orphan_saved"]
                  and report["orphan_entity_geometry_equal"]
                  and report["all_attached_resolve"]
                  and report["source_unchanged"])
        else:
            raise ValueError("EXPECTED_BASELINE_OR_PATCHED")
    report["status"] = "PASS" if ok else "FAIL"
    report["note"] = ("Native CADCraft read/save test, independent of original R5 DXF. "
                      "Does not certify full DXF version/codepage parity.")
    evidence.parent.mkdir(parents=True, exist_ok=True)
    evidence.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))
    return ok


def _block_signature(block) -> tuple:
    if block is None:
        return ()
    result = []
    for entity in block:
        if entity.dxftype() == "LINE":
            result.append(("LINE", tuple(round(float(v), 6) for v in entity.dxf.start),
                           tuple(round(float(v), 6) for v in entity.dxf.end)))
        elif entity.dxftype() == "CIRCLE":
            result.append(("CIRCLE", tuple(round(float(v), 6) for v in entity.dxf.center),
                           round(float(entity.dxf.radius), 6)))
        else:
            raise ValueError("UNEXPECTED_FIXTURE_BLOCK_ENTITY")
    return tuple(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="mode", required=True)
    p = sub.add_parser("patch")
    p.add_argument("root", type=Path)
    p = sub.add_parser("fixture")
    p.add_argument("folder", type=Path)
    p = sub.add_parser("verify")
    p.add_argument("cli", type=Path)
    p.add_argument("folder", type=Path)
    p.add_argument("--expect", choices=("baseline", "patched"), required=True)
    p.add_argument("--json", type=Path, required=True)
    args = parser.parse_args()
    if args.mode == "patch":
        print(json.dumps(patch_upstream(args.root), ensure_ascii=False))
    elif args.mode == "fixture":
        print(json.dumps(fixture(args.folder), ensure_ascii=False))
    else:
        raise SystemExit(0 if verify(args.cli, args.folder, args.expect, args.json) else 2)


if __name__ == "__main__":
    main()
